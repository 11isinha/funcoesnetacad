//12. **Construção de Nome Completo**
//    - Declare `fullName(firstName, lastName)` que retorne a concatenação dos nomes.
//    - Chame e imprima vários exemplos.
//    - *Tópicos:* parâmetros, return.

function fullName(firstName, lastName) {
  return firstName + " " + lastName;
}

console.log(fullName("Maria", "Duda"));
console.log(fullName("Ana", "Silva"));