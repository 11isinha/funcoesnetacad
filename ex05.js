//5. **Área do Círculo**
//    - Declare `calculateArea(radius)` que receba o raio de um círculo e retorne a área (`Math.PI * radius * radius`).
//    - Chame e imprima `calculateArea(2)`.
//    - *Tópicos:* parâmetros, return.

function calculateArea(radius) {
  return Math.PI * radius * radius;
}

